import React from 'react';

export interface TechIconProps {
  name: string;
  icon?: string | null;
  className?: string;
}

export function TechIcon({ name, icon, className = 'w-5 h-5' }: TechIconProps) {
  if (icon && (icon.startsWith('http://') || icon.startsWith('https://') || icon.startsWith('/'))) {
    return (
      <img
        src={icon}
        alt={name}
        className={`${className} object-contain`}
        loading="lazy"
      />
    );
  }

  const key = (icon || name || '').toLowerCase().trim();

  if (key === 'nodejs' || key === 'node.js' || key === 'node') {
    return <NodeJsIcon className={className} />;
  }
  if (key === 'postgresql' || key === 'postgres' || key === 'psql') {
    return <PostgreSqlIcon className={className} />;
  }
  if (key === 'prisma') {
    return <PrismaIcon className={className} />;
  }
  if (key === 'git' || key === 'github') {
    return <GitIcon className={className} />;
  }
  if (key === 'react' || key === 'react.js' || key === 'reactjs') {
    return <ReactIcon className={className} />;
  }
  if (key === 'typescript' || key === 'ts') {
    return <TypeScriptIcon className={className} />;
  }
  if (key === 'nextjs' || key === 'next.js' || key === 'next') {
    return <NextJsIcon className={className} />;
  }
  if (key === 'tailwindcss' || key === 'tailwind css' || key === 'tailwind') {
    return <TailwindCssIcon className={className} />;
  }

  return <FallbackIcon className={className} name={name} />;
}

